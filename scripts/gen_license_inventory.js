#!/usr/bin/env node
// Generates docs/THIRD_PARTY_LICENSES.md: license inventory of npm (production)
// and Rust (Cargo.lock) dependencies. Works offline from node_modules and
// ~/.cargo/registry/src. Run: node scripts/gen_license_inventory.js
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');

// ---------- npm (production closure) ----------
function readPkg(dir) {
  try { return JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8')); } catch { return null; }
}
function resolveDep(name, fromDir) {
  let dir = fromDir;
  for (;;) {
    const cand = path.join(dir, 'node_modules', name);
    if (fs.existsSync(path.join(cand, 'package.json'))) return cand;
    const parent = path.dirname(dir);
    if (parent === dir || parent.length < root.length) break;
    dir = parent;
  }
  const top = path.join(root, 'node_modules', name);
  return fs.existsSync(path.join(top, 'package.json')) ? top : null;
}
const rootPkg = readPkg(root);
const npm = new Map();
const queue = Object.keys(rootPkg.dependencies || {}).map((n) => [n, root]);
while (queue.length) {
  const [name, from] = queue.pop();
  const dir = resolveDep(name, from);
  if (!dir || npm.has(dir)) continue;
  const pkg = readPkg(dir);
  if (!pkg) continue;
  let lic = pkg.license || (pkg.licenses && pkg.licenses.map((l) => l.type).join(' OR ')) || 'UNKNOWN';
  if (typeof lic === 'object') lic = lic.type || 'UNKNOWN';
  npm.set(dir, { name: pkg.name, version: pkg.version, license: lic });
  for (const d of Object.keys(pkg.dependencies || {})) queue.push([d, dir]);
}

// ---------- Rust ----------
const lock = fs.readFileSync(path.join(root, 'src-tauri/Cargo.lock'), 'utf8');
const crates = [];
for (const block of lock.split('[[package]]').slice(1)) {
  const name = /name = "(.+?)"/.exec(block)?.[1];
  const version = /version = "(.+?)"/.exec(block)?.[1];
  const source = /source = "(.+?)"/.exec(block)?.[1];
  if (name && source) crates.push({ name, version });
}
const regRoot = path.join(os.homedir(), '.cargo/registry/src');
const regDirs = fs.existsSync(regRoot) ? fs.readdirSync(regRoot).map((d) => path.join(regRoot, d)) : [];
const rust = crates.map(({ name, version }) => {
  for (const r of regDirs) {
    const toml = path.join(r, `${name}-${version}`, 'Cargo.toml');
    if (fs.existsSync(toml)) {
      const t = fs.readFileSync(toml, 'utf8');
      const lic = /^license\s*=\s*"(.+?)"/m.exec(t)?.[1];
      const file = /^license-file\s*=\s*"(.+?)"/m.exec(t)?.[1];
      return { name, version, license: lic || (file ? `see ${file}` : 'UNKNOWN') };
    }
  }
  return { name, version, license: 'NOT-IN-LOCAL-CACHE' };
});

// ---------- output ----------
const sortBy = (a, b) => a.name.localeCompare(b.name);
const summary = (list) => {
  const m = new Map();
  for (const x of list) m.set(x.license, (m.get(x.license) || 0) + 1);
  return [...m.entries()].sort((a, b) => b[1] - a[1]).map(([l, c]) => `| ${l} | ${c} |`).join('\n');
};
const table = (list) => list.sort(sortBy).map((x) => `| ${x.name} | ${x.version} | ${x.license} |`).join('\n');
const flagged = [...npm.values(), ...rust].filter((x) =>
  /GPL|AGPL|SSPL|UNKNOWN|NOT-IN|see /i.test(x.license) && !/LGPL.*OR|OR.*LGPL/i.test(x.license));
const out = `# Third-Party License Inventory (auto-generated)

Generated by \`scripts/gen_license_inventory.js\`. Do not edit by hand; re-run before each release.
Full license texts must be shipped with release artifacts (see THIRD_PARTY_NOTICES.md).

## Items needing manual review
${flagged.length ? flagged.map((x) => `- ${x.name}@${x.version}: ${x.license}`).join('\n') : '- none'}

## npm production dependencies (${npm.size})
| License | Count |
|---|---|
${summary([...npm.values()])}

| Package | Version | License |
|---|---|---|
${table([...npm.values()])}

## Rust crates (${rust.length})
| License | Count |
|---|---|
${summary(rust)}

| Crate | Version | License |
|---|---|---|
${table(rust)}
`;
fs.writeFileSync(path.join(root, 'docs/THIRD_PARTY_LICENSES.md'), out);
console.log(`npm: ${npm.size}, rust: ${rust.length}, flagged: ${flagged.length}`);

